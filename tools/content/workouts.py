# Стартовая база тренировок Tempo.
#
# Функциональные: F(название, формат, параметры таймера, сложность, [(упражнение, дозировка), ...], описание)
#   FOR_TIME: cap=минуты лимита;  AMRAP: minutes;  EMOM: interval=сек, rounds;  TABATA: work, rest, rounds.
# Силовые: S(название, сложность, [(упражнение, подходы, повторы), ...], описание)
# Кардио: C(название, формат, сложность, [(упражнение, задание), ...], описание, параметры таймера)
#   INTERVALS: work, rest, rounds;  STEADY: minutes (непрерывная работа);  TABATA, FOR_TIME — как у функциональных.
# Сложность: 1 — лёгкая, 2 — средняя, 3 — тяжёлая.
# Дозировки «43/30 кг» — вес для мужчин / женщин.


def F(name, fmt, level, items, desc="", **timer):
    return dict(name=name, format=fmt, level=level, items=items, desc=desc, timer=timer)


def S(name, level, items, desc="", program=None):
    return dict(name=name, format="SETS", level=level, items=items, desc=desc, timer={}, program=program)


